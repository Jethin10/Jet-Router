import { readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const registryDir = join(scriptDir, "..", "open-sse", "providers", "registry");
const outputPath = join(registryDir, "index.js");

const files = readdirSync(registryDir)
  .filter((file) => file.endsWith(".js") && file !== "index.js")
  .sort((a, b) => a.localeCompare(b));

const imports = files
  .map((file, index) => `import p${index} from "./${file}";`)
  .join("\n");
const entries = files.map((_, index) => `  p${index},`).join("\n");

const output = `// Auto-generated by scripts/generate-registry-index.mjs
${imports}

export default [
${entries}
];
`;

writeFileSync(outputPath, output, "utf8");
console.log(`Generated ${outputPath} with ${files.length} providers`);
